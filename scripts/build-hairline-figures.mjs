/** Package the exact validated standalone figures; the upstream kernel stays byte-for-byte intact. */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = resolve(root, "docs/hairline-ui/v2/figures");
const target = resolve(root, "src/components/concepts/generated");
mkdirSync(target, { recursive: true });
const names = readdirSync(source).filter(name => name.endsWith(".js")).sort();
const figures = names.map(name => `  {\n${readFileSync(resolve(source, name), "utf8").trim()}\n  }`).join("\n");
writeFileSync(resolve(target, "figures.js"), `// Generated by scripts/build-hairline-figures.mjs. Edit the standalone sources.\nexport default function createFigures(HL) {\n  const figures = {};\n  const hairline = figure => { figures[figure.name] = figure; };\n${figures}\n  return figures;\n}\n`);
console.log(`Packaged ${names.length} Hairline figures: ${names.join(", ")}`);
